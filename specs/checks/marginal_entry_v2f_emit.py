#!/usr/bin/env python3
"""Emit Solution/MarginalEntryCert.lean: the kernel certificate for J_T[1, 1] at Table 3.

The closed form `jtSum 44 g L τ C 2 0` (BGP212/MarginalEntry.lean) is mirrored here in exact
rational arithmetic (standard library only). Each row `jtRow 44 r … = Σ_k C(44 − r, k) (−1)^k
pieceJ 44 r k …` is one `decide +kernel` lemma; the outer sum over `r` is assembled by `norm_num`.

Usage: python3 -I specs/checks/marginal_entry_v2f_emit.py [output path] [--rows a,b,...]
"""
import sys
from fractions import Fraction as Fr
from math import comb, factorial as fact

G, L, TAU = Fr(41, 625), Fr(53, 50), Fr(249, 250)
BNUM = [777, 794, 875, 917, 953, 983, 1016, 1042, 1063, 1081]
N = 44


def C(m):
    return Fr(0) if m == 0 else 4 * Fr(BNUM[min(m, 10) - 1], 5000)


def inner(X, D, p, t):
    return sum(comb(p, j) * D ** (p - j) * (-1) ** j * X ** (t + j + 1) / (t + j + 1) for j in range(p + 1))


def boxval(A, B, D, a, b):
    if not (A >= 0 and B >= 0):
        return Fr(0)
    E = max(Fr(0), min(A, D - B))
    F = max(Fr(0), min(A, D))
    return (B ** (b + 1) * E ** (a + 1) / (a + 1) + (inner(F, D, b + 1, a) - inner(E, D, b + 1, a))) / (b + 1)


def twopow(A, B, D, p, Lp, al, be, m1, m2):
    return sum(comb(m1, i) * p ** (m1 - i) * (-1) ** i * (comb(m2, j) * Lp ** (m2 - j) * (-1) ** j)
               * comb(j, l) * boxval(A, B, D, al + i + l, be + (j - l))
               for i in range(m1 + 1) for j in range(m2 + 1) for l in range(j + 1))


def cells(r, k, c, M, al, be, m, n):
    Lp = L - (r + k) * G
    c1 = C(r + 1) - (r + 1) * G
    c2 = L - k * G - C(r + 1)
    a = C(r + 1) - r * G
    A1 = min(c, c1)
    M3 = min(M, Lp - G)
    return (twopow(A1, c2, M, a, Lp, al, be, m, n)
            + (twopow(A1, M, M, 0, Lp, al, be, 0, m + n) - twopow(A1, c2, M, 0, Lp, al, be, 0, m + n))
            + G ** m * (twopow(c, M, M3, 0, Lp, al, be, 0, n) - twopow(A1, M, M3, 0, Lp, al, be, 0, n))
            + ((twopow(c, M, M, 0, Lp, al, be, 0, m + n) - twopow(A1, M, M, 0, Lp, al, be, 0, m + n))
               - (twopow(c, M, M3, 0, Lp, al, be, 0, m + n) - twopow(A1, M, M3, 0, Lp, al, be, 0, m + n))))


def seg0(k, M, be, m, n):
    Lp = L - k * G
    X = max(Fr(0), min(L - k * G - C(1), M))
    return C(1) ** m * inner(X, Lp, n, be) + (inner(M, Lp, m + n, be) - inner(X, Lp, m + n, be))


def pieceJ(r, k, m=2, n=0):
    if C(r) - r * G < 0 or TAU - (r + k) * G < 0:
        return Fr(0)
    if r == 0:
        return Fr(1, fact(N - 1)) * seg0(k, TAU - k * G, N - 1, m, n)
    return Fr(1, fact(r - 1)) * Fr(1, fact(N - r - 1)) * cells(r, k, C(r) - r * G, TAU - (r + k) * G,
                                                             r - 1, N - r - 1, m, n)


def row(r):
    return sum(comb(N - r, k) * (-1) ** k * pieceJ(r, k) for k in range(N - r + 1))


def lit(x):
    x = Fr(x)
    return f"({x.numerator} : ℚ)" if x.denominator == 1 else f"({x.numerator} / {x.denominator} : ℚ)"


HEADER = """/-
Copyright (c) 2026 thinkthoughts. All rights reserved.
Released under MIT license as described in the file LICENSE.
Source: Axiom Math, "A New Bound for Small Gaps Between Primes", preliminary draft
(September 3, 2026): Table 3 (p. 39), §9.4, Lemma 9.2 and the display of `J_T` (p. 41).
-/
import BGP212.MarginalEntry

/-! # V2f: the kernel certificate for `J_T[1, 1]` at Table 3

COMPUTATIONAL CERTIFICATE (generated by `specs/checks/marginal_entry_v2f_emit.py`). The closed form
`jtSum 44 g L τ C 2 0` (Table 3 data from `BGP212.Params`) is evaluated over `ℚ`:

* the 133 nonempty pieces `(r, k)` (`r ≤ 13`, `r + k ≤ 15`) are evaluated by the Lean kernel, one
  `decide +kernel` lemma `pj_r_k` per piece;
* every other piece vanishes by `pieceJ_tail` (`τ < (r + k) g` once `r + k ≥ 16`) or
  `pieceJ_high` (`C(r) < r g` once `r ≥ 14`), proved by linear arithmetic;
* rows and the total are assembled by `decide +kernel` on the resulting numerals.

The integral identity that gives this number its meaning, `jT_one_eq`, is proved in
`Solution/MarginalEntry.lean`. -/

namespace BGP212.V2e

open BGP212.Params

/-- Pieces with `r + k ≥ 16` are empty at Table 3 (`τ − 16 g = −53/1250`). -/
theorem pieceJ_tail (r k : ℕ) (h : 16 ≤ r + k) : pieceJ 44 r k g L τ C 2 0 = 0 := by
  unfold pieceJ
  rw [if_pos (Or.inr ?_)]
  have : (16 : ℚ) ≤ r + k := by exact_mod_cast h
  rw [show τ = 249 / 250 from rfl, show g = 41 / 625 from rfl]
  linarith

/-- Pieces with `r ≥ 14` are empty at Table 3 (`C(r) = 1081/1250 < 14 g`). -/
theorem pieceJ_high (r k : ℕ) (h : 14 ≤ r) : pieceJ 44 r k g L τ C 2 0 = 0 := by
  unfold pieceJ
  rw [if_pos (Or.inl ?_)]
  have hr : (14 : ℚ) ≤ r := by exact_mod_cast h
  have hC : C r = 4 * (1081 / 5000) := by
    rw [C, B, if_neg (by omega), if_neg (by omega)]
  rw [hC, show g = 41 / 625 from rfl]
  linarith

/-- `jtSum` as a sum of rows (definitional). -/
theorem jtSum_eq_rows {K : Type*} [Field K] [LinearOrder K] (N : ℕ) (g L τ : K) (C : ℕ → K)
    (m n : ℕ) : jtSum N g L τ C m n =
      (N + 1) * ∑ r ∈ Finset.range (N + 1), (N.choose r : K) * jtRow N r g L τ C m n := rfl

theorem jtRow_high (r : ℕ) (h : 14 ≤ r) : jtRow 44 r g L τ C 2 0 = 0 :=
  Finset.sum_eq_zero fun k _ => by rw [pieceJ_high r k h, mul_zero]
"""


def main():
    out = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("--") else "Solution/MarginalEntryCert.lean"
    only = None
    if "--pieces" in sys.argv:
        only = [tuple(int(v) for v in x.split(":")) for x in sys.argv[sys.argv.index("--pieces") + 1].split(",")]
    lines = [HEADER]
    vals = {}
    for r in range(14):
        for k in range(16 - r):
            vals[(r, k)] = pieceJ(r, k)
    pieces = only if only else sorted(vals)
    for (r, k) in pieces:
        lines.append(f"theorem pj_{r}_{k} : pieceJ 44 {r} {k} g L τ C 2 0 = {lit(vals[(r, k)])} := by\n"
                     "  decide +kernel\n")
    if only is None:
        rowv = {}
        for r in range(14):
            K = 16 - r                       # nonzero k: 0 … 15 − r
            rowv[r] = sum(comb(N - r, k) * (-1) ** k * vals[(r, k)] for k in range(K))
            tail = (N - r + 1) - K
            names = ", ".join(f"pj_{r}_{k}" for k in range(K))
            lines.append(
                f"theorem jtRow_{r} : jtRow 44 {r} g L τ C 2 0 = {lit(rowv[r])} := by\n"
                f"  have hz : ∑ x ∈ Finset.range {tail}, (((44 - {r}).choose ({K} + x) : ℕ) : ℚ) *\n"
                f"      (-1) ^ ({K} + x) * pieceJ 44 {r} ({K} + x) g L τ C 2 0 = 0 :=\n"
                f"    Finset.sum_eq_zero fun x _ => by rw [pieceJ_tail {r} ({K} + x) (by omega), mul_zero]\n"
                f"  rw [jtRow, show 44 - {r} + 1 = {K} + {tail} from rfl, Finset.sum_range_add, hz, add_zero]\n"
                f"  simp only [Finset.sum_range_succ, Finset.sum_range_zero, {names}]\n"
                "  decide +kernel\n")
        total = (N + 1) * sum(comb(N, r) * rowv[r] for r in range(14))
        assert total == (N + 1) * sum(comb(N, r) * row(r) for r in range(N + 1))
        lines.append(
            "/-- **`J_T[1, 1]` at Table 3** as a rational. -/\n"
            f"theorem jtSum_table3 : jtSum 44 g L τ C 2 0 = {lit(total)} := by\n"
            "  have hz : ∑ x ∈ Finset.range 31, ((Nat.choose 44 (14 + x) : ℕ) : ℚ) *\n"
            "      jtRow 44 (14 + x) g L τ C 2 0 = 0 :=\n"
            "    Finset.sum_eq_zero fun x _ => by rw [jtRow_high (14 + x) (by omega), mul_zero]\n"
            "  rw [jtSum_eq_rows, show 44 + 1 = 14 + 31 from rfl, Finset.sum_range_add, hz, add_zero]\n"
            "  simp only [Finset.sum_range_succ, Finset.sum_range_zero, "
            + ", ".join(f"jtRow_{r}" for r in range(14)) + "]\n"
            "  decide +kernel\n")
        print("J_T[1,1] =", float(total))
        print("value", total.numerator, "/", total.denominator)
    lines.append("end BGP212.V2e\n")
    open(out, "w").write("\n".join(lines))
    print("wrote", out, "with", len(pieces), "piece lemmas")


if __name__ == "__main__":
    main()
