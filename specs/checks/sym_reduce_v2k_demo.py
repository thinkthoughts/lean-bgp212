"""Emit V2k's kernel demonstration (Solution/SymReduceDemo1.lean, Solution/SymReduceDemo2.lean).

Demo1 — small certified examples (rational oracle `demoM`, class sizes `demoN = (3, 2, 4)`,
shifted power sums `demoF qs`):
  * transition tables `psTrans` (`p_α = Σ_ν R_{α,ν} m̃_ν`) for three products of class power sums;
  * agreement on small products: V2i's `placeVal` and V2k's `symPlaceVal`, each evaluated by the
    kernel, give the same rational (degrees 4 and 6);
  * higher degrees (8, 10, 10): `symPlaceVal` by the kernel, and V2i's `placeVal` value through the
    general theorem `symPlaceVal_eq` (no evaluation of the placement recursion).

Demo2 — Table 3 data and the synthetic entry, reusing V2j's certified moments:
  * `genTable` of J_T[P₂, P₂] on piece (6, 3) (19 keys) and the piece value, identical to V2i's
    `gpPP_6_3` (`rfl` on the statements);
  * `aggTable` of V2i's four entries on piece (6, 3) (21 keys), identical to V2j's `agg4_6_3_eq`;
  * `genTable` of J_T[P_(2,2), P_(2,2)] on piece (6, 3): all 85 moment coefficients from one kernel
    evaluation, and the piece as an explicit combination of 85 moments;
  * the synthetic N = 3 entry J_T[P₂, P₂] from the ten piece tables, identical to V2j's
    `genEntrySmall_PP`.

Usage: python3 -I specs/checks/sym_reduce_v2k_demo.py [outdir]
"""
