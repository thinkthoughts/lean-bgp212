def mo_name(N, r, k, s):
    return f"mo_{N}_{r}_{k}_{s[0]}_{s[1]}_{s[2]}_{s[3]}"


def tv_block(name, T, N, r, k, gL, dataL, out):
    """tableVal of a literal table against pieceMn, from the V2j moment lemmas."""
    names = [mo_name(N, r, k, s) for s, v in T if v != 0]
    total = Fr(0)
    for s, v in T:
        if v != 0:
            total += v * Q.pieceMn(r, k, *s)
    zm = " zero_mul," if any(v == 0 for _, v in T) else ""
    out.append(f"theorem {name} : tableVal ({table_lit(T)} : List (MKey × ℚ))\n"
               f"    (fun A B m n => pieceMn {N} {r} {k} A B {gL} {dataL} m n) = {lit(total)} := by\n"
               f"  simp only [tableVal, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil,{zm}\n"
               f"    {', '.join(names)}]\n  norm_num\n")
    return total


def demo2(out):
    out.append(HDR + """import Solution.SymReduce
import Solution.MomentAggDemo3
import Solution.MomentAggDemo4

/-! # V2k: moment-coefficient tables at Table 3 and on synthetic data

COMPUTATIONAL DEMONSTRATION (generated by `specs/checks/sym_reduce_v2k_demo.py`). Each `tab_*` is one
kernel evaluation of V2k's `genTable` / `aggTable` (all moment coefficients of a piece at once);
the moments are V2j's certified `mo_*` lemmas.

* `genPiecePP_6_3_viaTable`: piece `(6, 3)` of `J_T[P₂, P₂]` at Table 3, the same statement as V2i's
  `gpPP_6_3`;
* `agg4_6_3_viaTable`: V2i's four entries on that piece, the same statement as V2j's `agg4_6_3_eq`;
* `tab_P22_6_3`, `genPieceP22_6_3_expansion`: piece `(6, 3)` of `J_T[P_(2,2), P_(2,2)]` (degree 8)
  as an explicit combination of 85 moments;
* `genEntrySmall_PP_viaTable`: the synthetic `N = 3` entry `J_T[P₂, P₂]`, the same statement as
  V2j's `genEntrySmall_PP`. -/

namespace BGP212.V2e

open BGP212.Params

""")
    # Table 3, piece (6, 3)
    T = S.gen_table(6, 3, 0, [2], 0, [2])
    out.append(f"/-- All 19 moment coefficients of piece `(6, 3)` of `J_T[P₂, P₂]` at Table 3. -/\n"
               f"theorem tab_PP_6_3 : genTable 44 6 3 g 0 [2] 0 [2] =\n    ({table_lit(T)} : List (MKey × ℚ)) := by\n"
               f"  decide +kernel\n")
    vPP = tv_block("tv_PP_6_3", T, 44, 6, 3, "g", "L τ C", out)
    assert vPP == Q.genPiece(6, 3, 0, [2], 0, [2])
    out.append(f"""theorem genPiecePP_6_3_viaTable : genPiece 44 6 3 g L τ C 0 [2] 0 [2] = {lit(vPP)} :=
  (genPieceWith_eq_table 44 6 3 g _ 0 [2] 0 [2]).trans
    ((congrArg (fun T => tableVal T (fun A B m n => pieceMn 44 6 3 A B g L τ C m n)) tab_PP_6_3).trans
      tv_PP_6_3)

/-- The table route proves exactly V2i's certified statement `gpPP_6_3`. -/
theorem genPiecePP_6_3_table_same_as_v2i : genPiecePP_6_3_viaTable = gpPP_6_3 := rfl
""")
    ws = [(Fr(1),) + e for e in ALL]
    T4 = S.agg_table(6, 3, ws)
    out.append(f"/-- The 21 shared moment coefficients of V2i's four entries on piece `(6, 3)`. -/\n"
               f"theorem tab_ALL_6_3 : aggTable 44 6 3 g {ws_lit(ALL)} =\n    ({table_lit(T4)} : List (MKey × ℚ)) := by\n"
               f"  decide +kernel\n")
    v4 = tv_block("tv_ALL_6_3", T4, 44, 6, 3, "g", "L τ C", out)
    out.append(f"""theorem agg4_6_3_viaTable : (List.map (fun w : WPair ℚ => w.1 * genPieceWith 44 6 3 g
    (fun A B m n => pieceMn 44 6 3 A B g L τ C m n) w.2.1 w.2.2.1 w.2.2.2.1 w.2.2.2.2) {ws_lit(ALL)}).sum =
    {lit(v4)} :=
  (aggTable_eq 44 6 3 g {ws_lit(ALL)} _).trans
    ((congrArg (fun T => tableVal T (fun A B m n => pieceMn 44 6 3 A B g L τ C m n)) tab_ALL_6_3).trans
      tv_ALL_6_3)

/-- The same statement as V2j's `agg4_6_3_eq`. -/
theorem agg4_6_3_table_same_as_v2j : agg4_6_3_viaTable = agg4_6_3_eq := rfl
""")
    T22 = S.gen_table(6, 3, 0, [2, 2], 0, [2, 2])
    out.append(f"/-- All 85 moment coefficients of piece `(6, 3)` of `J_T[P_(2,2), P_(2,2)]` (degree 8) at "
               f"Table 3, from one kernel evaluation. -/\n"
               f"theorem tab_P22_6_3 : genTable 44 6 3 g 0 [2, 2] 0 [2, 2] =\n    ({table_lit(T22)} : List (MKey × ℚ)) := by\n"
               f"  decide +kernel\n")
    out.append(f"""/-- **Piece `(6, 3)` of `J_T[P_(2,2), P_(2,2)]` as an explicit combination of 85 moments.** -/
theorem genPieceP22_6_3_expansion : genPiece 44 6 3 g L τ C 0 [2, 2] 0 [2, 2] =
    tableVal ({table_lit(T22)} : List (MKey × ℚ))
      (fun A B m n => pieceMn 44 6 3 A B g L τ C m n) :=
  (genPieceWith_eq_table 44 6 3 g _ 0 [2, 2] 0 [2, 2]).trans
    (congrArg (fun T => tableVal T (fun A B m n => pieceMn 44 6 3 A B g L τ C m n)) tab_P22_6_3)
""")
    # synthetic N = 3
    CS = [Fr(0), Fr(1, 2), Fr(3, 5), Fr(7, 10)]
    Q.setdata(3, Fr(3, 10), Fr(1), Fr(9, 10), lambda m: CS[min(m, 3)])
    pieces = [(r, k) for r in range(4) for k in range(4 - r)]
    vals = {}
    for (r, k) in pieces:
        T = S.gen_table(r, k, 0, [2], 0, [2])
        out.append(f"theorem tab_S_{r}_{k} : genTable 3 {r} {k} (3 / 10 : ℚ) 0 [2] 0 [2] =\n"
                   f"    ({table_lit(T)} : List (MKey × ℚ)) := by\n  decide +kernel\n")
        v = tv_block(f"tvx_S_{r}_{k}", T, 3, r, k, "(3 / 10 : ℚ)", "1 (9 / 10) synthC", out)
        out.append(f"theorem tv_S_{r}_{k} : tableVal (genTable 3 {r} {k} (3 / 10 : ℚ) 0 [2] 0 [2])\n"
                   f"    (fun A B m n => pieceMn 3 {r} {k} A B (3 / 10 : ℚ) 1 (9 / 10) synthC m n) = {lit(v)} := by\n"
                   f"  rw [tab_S_{r}_{k}]; exact tvx_S_{r}_{k}\n")
        assert v == Q.genPiece(r, k, 0, [2], 0, [2])
        vals[(r, k)] = v
    small = 4 * sum(comb(3, r) * comb(3 - r, k) * (-1) ** k * vals[(r, k)] for (r, k) in pieces)
    names = ", ".join(f"tv_S_{r}_{k}" for (r, k) in pieces)
    out.append(f"""/-- The synthetic entry from its ten piece tables: the same statement as V2j's
`genEntrySmall_PP` (V2h's synthetic value). -/
theorem genEntrySmall_PP_viaTable : genEntryVal 3 (3 / 10 : ℚ) 1 (9 / 10) synthC 0 [2] 0 [2] = {lit(small)} := by
  rw [genEntryVal_eq_table]
  simp only [Finset.sum_range_succ, Finset.sum_range_zero, Nat.reduceSub, Nat.reduceAdd, {names}]
  norm_num

theorem genEntrySmall_PP_table_same_as_v2j : genEntrySmall_PP_viaTable = genEntrySmall_PP := rfl
""")
    out.append("end BGP212.V2e\n")
    return T22


