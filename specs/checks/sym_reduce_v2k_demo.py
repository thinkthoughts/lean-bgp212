def lit(x):
    x = Fr(x)
    return f"({x.numerator} : ℚ)" if x.denominator == 1 else f"({x.numerator} / {x.denominator} : ℚ)"


def rlit(x):
    x = Fr(x)
    return f"{x.numerator}" if x.denominator == 1 else f"{x.numerator} / {x.denominator}"


def ll(l):
    return "[" + ", ".join(map(str, l)) + "]"


def skey(k):
    return "[" + ", ".join(f"({c}, {e})" for c, e in k) + "]"


def trans_lit(L):
    return "[" + ", ".join(f"({skey(k)}, {rlit(v)})" for k, v in L) + "]"


def table_lit(T):
    return "[" + ",\n    ".join(f"(({a}, {b}, {m}, {n}), {rlit(v)})" for (a, b, m, n), v in T) + "]"


def ws_lit(entries):
    return "[" + ", ".join(f"((1 : ℚ), {a1}, {ll(l1)}, {a2}, {ll(l2)})" for (a1, l1, a2, l2) in entries) + "]"


