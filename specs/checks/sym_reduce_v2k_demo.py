ALL = [(0, [2], 0, [2]), (0, [4], 0, []), (0, [2, 2], 0, []), (1, [], 0, [])]


def demo_m(A, B):
    return Fr(1, (A + 1) * (B + 2) + A * B + 3)


def sig_factors(qs, g=Fr(3, 10)):
    sig = [g, g, Fr(0)]
    return [(lambda c, q=q: Q.shiftPow(sig[c], q)) for q in qs]


def demo1(out):
    n = [3, 2, 4]
    out.append(HDR + """import Solution.SymReduce

/-! # V2k: small certified examples of the symmetric-function evaluator

COMPUTATIONAL DEMONSTRATION (generated by `specs/checks/sym_reduce_v2k_demo.py`), on the example
data `demoN = (3, 2, 4)`, `demoM`, `demoF` of `BGP212/SymReduce.lean`:

* transition tables `psTrans` (`p_α = Σ_ν R_{α,ν} m̃_ν`, states as canonical lists of parts);
* degrees 4 and 6: V2i's placement value and V2k's value, each evaluated by the kernel, agree;
* degree 8: V2k's value by the kernel; V2i's statement through `symPlaceVal_eq`
  (degree 10 in `Solution/SymReduceDemo3.lean`, a separate `lean` process). -/

namespace BGP212.V2e

""")
    for name, alpha, doc in [
            ("trans_p2_p2", [(0, 2), (0, 2)], "`p₂² = m̃_(4) + m̃_(2,2)` in one class."),
            ("trans_p1_cubed", [(0, 1), (0, 1), (0, 1)],
             "`p₁³ = m̃_(3) + 3 m̃_(2,1) + m̃_(1,1,1)` in one class."),
            ("trans_mixed", [(0, 2), (1, 1), (0, 1)],
             "`p_{0,2} p_{1,1} p_{0,1}` across two classes.")]:
        L = S.ps_trans(alpha)
        out.append(f"/-- **Transition.** {doc} -/\ntheorem {name} : psTrans (K := ℚ) demoN "
                   f"{skey(alpha)} =\n    ({trans_lit(L)} : List (SKey × ℚ)) := by\n  decide +kernel\n")
    for qs in ([2, 2], [2, 2, 2]):
        v = S.sym_place_val(demo_m, n, sig_factors(qs))
        assert v == Q.Phi(demo_m, n, [], sig_factors(qs))
        tag = "".join(map(str, qs))
        out.append(f"/-- V2i's placement recursion, evaluated by the kernel (degree {sum(qs)}). -/\n"
                   f"theorem demo_place_{tag} : placeVal demoM demoN 0 Fin.elim0 Fin.elim0 (demoF {ll(qs)}) =\n"
                   f"    {lit(v)} := by\n  decide +kernel\n")
        out.append(f"/-- V2k's evaluator, evaluated by the kernel: the same value. -/\n"
                   f"theorem demo_sym_{tag} : symPlaceVal demoM demoN (demoF {ll(qs)}) = {lit(v)} := by\n"
                   f"  decide +kernel\n")
    high(out, [2, 2, 2, 2])
    out.append("end BGP212.V2e\n")


