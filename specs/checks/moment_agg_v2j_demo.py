def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "Solution"
    here = os.path.dirname(os.path.abspath(__file__))
    cert = open(os.path.join(here, "../../Solution/GenEntryCert6.lean")).read()
    v2i = {}
    for name, args in ENTRIES:
        m = re.search(rf"theorem gp{name}_6_3 : genPiece[^=]*= \((\d+(?: / \d+)?) : ℚ\)", cert)
        v2i[name] = Fr(m.group(1).replace(" ", ""))
    out = [HDR]
    mo = {}
    files = []
    nxt = [HDR2.format(prev="Solution.MomentAggDemo1")]
    S1, ws1, t1 = piece_block("PP_6_3", 6, 3, ENTRIES[:1], 44, "g", "L τ C", mo, out, nxt)
    assert t1 == v2i["PP"]
    out.append("end BGP212.V2e\n")
    files.append(out)
    out = nxt
    out.append(f"""theorem genPiecePP_6_3_viaAgg : genPiece 44 6 3 g L τ C 0 [2] 0 [2] = {lit(t1)} :=
  (genPiece_eq_aggPieceOn {S1} nd_PP_6_3 44 6 3 g L τ C 0 [2] 0 [2] cov_PP_6_3).trans agg_PP_6_3

/-- The recomputation proves exactly V2i's certified statement `gpPP_6_3`. -/
theorem genPiecePP_6_3_same_as_v2i : genPiecePP_6_3_viaAgg = gpPP_6_3 := rfl
""")
    nxt = [HDR2.format(prev="Solution.MomentAggDemo2")]
    S4, ws4, t4 = piece_block("ALL_6_3", 6, 3, ENTRIES, 44, "g", "L τ C", mo, out, nxt)
    assert t4 == sum(v2i.values())
    out.append("end BGP212.V2e\n")
    files.append(out)
    out = nxt
    out.append(f"""/-- The four V2i entries on piece `(6, 3)`: `Σ_{{w ∈ ws}} w · genPieceWith … = …` from 21 shared keys. -/
theorem agg4_6_3_eq : (List.map (fun w : WPair ℚ => w.1 * genPieceWith 44 6 3 g
    (fun A B m n => pieceMn 44 6 3 A B g L τ C m n) w.2.1 w.2.2.1 w.2.2.2.1 w.2.2.2.2) {ws4}).sum =
    {lit(t4)} :=
  (aggPieceOn_eq {S4} nd_ALL_6_3 44 6 3 g {ws4} cov_ALL_6_3
    (fun A B m n => pieceMn 44 6 3 A B g L τ C m n)).symm.trans agg_ALL_6_3
""")
    out.append("end BGP212.V2e\n")
    files.append(out)
    out = [HDR2.format(prev="Solution.MomentAgg")]
    CS = [Fr(0), Fr(1, 2), Fr(3, 5), Fr(7, 10)]
    Q.setdata(3, Fr(3, 10), Fr(1), Fr(9, 10), lambda m: CS[min(m, 3)])
    pieces = [(r, k) for r in range(4) for k in range(4 - r)]
    vals = {}
    Ss = wsS = None
    for (r, k) in pieces:
        Ss, wsS, v = piece_block(f"S_{r}_{k}", r, k, ENTRIES[:1], 3, "(3 / 10 : ℚ)", "1 (9 / 10) synthC", mo, out)
        vals[(r, k)] = v
    small = 4 * sum(comb(3, r) * comb(3 - r, k) * (-1) ** k * vals[(r, k)] for (r, k) in pieces)
    names = ", ".join(f"agg_S_{r}_{k}" for (r, k) in pieces)
    out.append(f"""theorem aggSmall_PP : aggEntryValOn {Ss} 3 (3 / 10 : ℚ) 1 (9 / 10) synthC {wsS} = {lit(small)} := by
  simp only [aggEntryValOn, Finset.sum_range_succ, Finset.sum_range_zero, Nat.reduceSub, Nat.reduceAdd,
    {names}]
  norm_num

theorem genEntrySmall_PP : genEntryVal 3 (3 / 10 : ℚ) 1 (9 / 10) synthC 0 [2] 0 [2] = {lit(small)} :=
  (genEntryVal_eq_aggEntryValOn {Ss} nd_S_0_0 3 (3 / 10 : ℚ) 1 (9 / 10) synthC 0 [2] 0 [2] cov_S_0_0).trans
    aggSmall_PP
""")
    out.append("end BGP212.V2e\n")
    files.append(out)
    for i, f in enumerate(files, 1):
        open(os.path.join(out_dir, f"MomentAggDemo{i}.lean"), "w").write("\n".join(f))
    print("wrote", out_dir, "| moments evaluated:", len(mo), "| PP piece", float(t1), "| four entries",
          float(t4), "| synthetic J[P2,P2]", float(small))


if __name__ == "__main__":
    main()
