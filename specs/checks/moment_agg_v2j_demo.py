#!/usr/bin/env python3
"""Emit V2j's kernel demonstration (Solution/MomentAggDemo1.lean … MomentAggDemo4.lean; evaluations
and assemblies in separate files so that each `lean` process stays within memory).

The certificate is staged so that every kernel evaluation is a separate declaration:
  * `nd_*`, `cov_*`: the key list S is duplicate-free and contains every queried key
    (`decide`; these are the hypotheses of `aggPieceOn_eq`);
  * `ck_*`: the collapsed coefficient `aggCoeff … s` of each key (no moment is evaluated);
  * `mo_*`: each distinct moment `pieceMn … s`, evaluated once, directly from V2f's cells;
  * `agg_*`: the aggregated sum `aggPieceOn S …` assembled from those numerals (`norm_num`);
  * the link to V2i through `aggPieceOn_eq`.

Demonstrations:
  * piece (r, k) = (6, 3) at Table 3, J_T[P₂, P₂]: 19 moments; the resulting statement is V2i's
    certified `gpPP_6_3` (checked by `rfl` on the proofs, i.e. identical statements), recomputed
    independently of V2h's moment lemmas;
  * the same piece for V2i's four entries together (PP, P4, P22, LP): 21 shared keys, 2 new
    moments, equal to the sum of the four V2i piece values;
  * synthetic N = 3: every piece of J_T[P₂, P₂], then the whole entry `aggEntryValOn`, equal to V2h's
    synthetic value, and V2i's `genEntryVal` through `aggEntryValOn_eq`.

Usage: python3 -I specs/checks/moment_agg_v2j_demo.py [outdir]
"""
import os
import re
import sys
from fractions import Fraction as Fr
from math import comb

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_entry_v2i_model as Q  # noqa: E402

ENTRIES = [("PP", (0, [2], 0, [2])), ("P4", (0, [4], 0, [])), ("P22", (0, [2, 2], 0, [])),
           ("LP", (1, [], 0, []))]


def lit(x):
    x = Fr(x)
    return f"({x.numerator} : ℚ)" if x.denominator == 1 else f"({x.numerator} / {x.denominator} : ℚ)"


def ll(l):
    return "[" + ", ".join(map(str, l)) + "]"


def wl(entries):
    return "[" + ", ".join(f"((1 : ℚ), {a1}, {ll(l1)}, {a2}, {ll(l2)})" for _, (a1, l1, a2, l2) in entries) + "]"


def klist(ks):
    return "[" + ", ".join(f"({a}, {b}, {m}, {n})" for (a, b, m, n) in ks) + "]"


def coeff(r, k, entries, s):
    return sum(Q.genPiece(r, k, *args, Mo=lambda A, B, m, n: Fr(1) if (A, B, m, n) == s else Fr(0))
               for _, args in entries)


def keyset(entries):
    ks = set()
    for _, args in entries:
        ks |= set(Q.keys(*args))
    return sorted(ks)


def piece_block(tag, r, k, entries, N, gL, dataL, mo_names, out, asm_out=None):
    """Emit coefficient lemmas, missing moment lemmas, and the assembly for one piece."""
    ks = keyset(entries)
    S = klist(ks)
    ws = wl(entries)
    out.append(f"theorem nd_{tag} : ({S} : List MKey).Nodup := by decide\n")
    out.append(f"theorem cov_{tag} : ∀ w ∈ ({ws} : List (WPair ℚ)), ∀ s ∈ genKeys {gL} w.2.1 w.2.2.1 "
               f"w.2.2.2.1 w.2.2.2.2, s ∈ ({S} : List MKey) := by\n  decide +kernel\n")
    names = []
    total = Fr(0)
    for i, s in enumerate(ks):
        c = coeff(r, k, entries, s)
        out.append(f"theorem ck_{tag}_{i} : aggCoeff {N} {r} {k} {gL} {ws} {s} = {lit(c)} := by\n  decide +kernel\n")
        names.append(f"ck_{tag}_{i}")
        key = (N, r, k, s)
        if key not in mo_names:
            v = Q.pieceMn(r, k, *s)
            nm = f"mo_{N}_{r}_{k}_{s[0]}_{s[1]}_{s[2]}_{s[3]}"
            out.append(f"theorem {nm} : pieceMn {N} {r} {k} {s[0]} {s[1]} {gL} {dataL} {s[2]} {s[3]} = "
                       f"{lit(v)} := by\n  decide +kernel\n")
            mo_names[key] = (nm, v)
        names.append(mo_names[key][0])
        total += c * mo_names[key][1]
    asm = (f"theorem agg_{tag} : aggPieceOn {S} {N} {r} {k} {gL} {ws}\n"
               f"    (fun A B m n => pieceMn {N} {r} {k} A B {gL} {dataL} m n) = {lit(total)} := by\n"
               f"  simp only [aggPieceOn, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil,\n"
               f"    {', '.join(names)}]\n  norm_num\n")
    if asm_out is None:
        out.append(asm)
    else:
        asm_out.append(asm)
    return S, ws, total


