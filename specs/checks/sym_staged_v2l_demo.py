def staged_table(run, ws):
    """Mirror of Lean's stagedTable with the runs of `run` (all-2 factor lists)."""
    groups = {}
    for (w, a1, l1, a2, l2) in ws:
        for (K1, p1, q1, c1) in Q.innerTerms(a1, l1):
            for (K2, p2, q2, c2) in Q.innerTerms(a2, l2):
                key = (tuple(sorted(K1 + K2, reverse=True)), p1 + p2, q1 + q2)
                groups[key] = groups.get(key, Fr(0)) + w * c1 * c2
    acc = {}
    for (Qd, m, nn), c in sorted(groups.items()):
        assert all(q == 2 for q in Qd)
        for st, kap in run.L[len(Qd)]:
            A, B = S.key_AB(st)
            s = (A, B, m, nn)
            acc[s] = acc.get(s, Fr(0)) + c * kap * S.factW(st)
    return sorted(acc.items())


def prof(L):
    """Mirror of `abProfile`."""
    acc = {}
    for k, kap in L:
        ab = S.key_AB(k)
        acc[ab] = acc.get(ab, Fr(0)) + kap * S.factW(k)
    return sorted(acc.items())


def penc(P):
    out = []
    for (a, b), v in P:
        v = Fr(v)
        out.append(f"[{a}, {b}, {0 if v >= 0 else 1}, {abs(v.numerator)}, {v.denominator}]")
    return "decProf [" + ", ".join(out) + "]"


def prof_table(run, ws):
    """Mirror of Lean's profTable with the profiles of `run`."""
    groups = {}
    for (w, a1, l1, a2, l2) in ws:
        for (K1, p1, q1, c1) in Q.innerTerms(a1, l1):
            for (K2, p2, q2, c2) in Q.innerTerms(a2, l2):
                key = (tuple(sorted(K1 + K2, reverse=True)), p1 + p2, q1 + q2)
                groups[key] = groups.get(key, Fr(0)) + w * c1 * c2
    acc = {}
    for (Qd, m, nn), c in sorted(groups.items()):
        for (A, B), v in prof(run.L[len(Qd)]):
            acc[(A, B, m, nn)] = acc.get((A, B, m, nn), Fr(0)) + c * v
    return sorted(acc.items())


def write_profiles(root, run):
    """Certified moment profiles of the runs P̂₂^k, k ≤ 6, at Table 3."""
    d = os.path.join(root, "Solution", "SymStagedCert")
    t = run.tag
    o = [HDR + f"import Solution.SymStagedCert.{t}Run5\n\n"
         f"/-! # V2ℓ: certified moment profiles of the run `{t}`, factors 0–5 (generated by\n"
         "`specs/checks/sym_staged_v2l_demo.py`) -/\n\nnamespace BGP212.V2e\n\n" + run.opens]
    for k in range(0, 6):
        P = prof(run.L[k])
        Lk = "[([], 1)]" if k == 0 else run.name(k)
        ch = f"(chainCert_nil {run.nE} [([], 1)])" if k == 0 else f"{t}_c{k}"
        o.append(f"def {t}_P{k} : List ((ℕ × ℕ) × ℚ) := {penc(P)}\n")
        o.append(f"theorem {t}_pc{k} : ProfCert {run.nE} {run.gE} {qlit(k)} {t}_P{k} :=\n"
                 f"  profCert_of_chain _ _ _ {Lk} _ {ch} (by decide +kernel)\n")
    o.append("end BGP212.V2e\n")
    open(os.path.join(d, f"{t}Prof.lean"), "w").write("\n".join(o))
    cs = run.chunks[6]
    groups = [list(range(i, min(i + 4, len(cs)))) for i in range(0, len(cs), 4)]
    Ps = [prof(c) for c in cs]
    for gi, grp in enumerate(groups):
        o = [HDR + f"import Solution.SymStaged\nimport Solution.SymStagedCert.{t}Run6D\n\n"
             f"/-! # V2ℓ: moment profiles of the degree-12 states of `{t}`, chunks {grp[0]}–{grp[-1]}\n"
             "(generated by `specs/checks/sym_staged_v2l_demo.py`) -/\n\nnamespace BGP212.V2e\n"]
        for j in grp:
            o.append(f"def {t}_P6_{j} : List ((ℕ × ℕ) × ℚ) := {penc(Ps[j])}\n")
            o.append(f"theorem {t}_pq6_{j} : abProfile {run.name(6, j)} = {t}_P6_{j} := by\n  decide +kernel\n")
        o.append("end BGP212.V2e\n")
        open(os.path.join(d, f"{t}Prof6G{gi}.lean"), "w").write("\n".join(o))
    P6 = prof(run.L[6])
    assert merge_profiles(Ps) == P6
    f2 = "".join(f"(List.Forall₂.cons {t}_pq6_{j} " for j in range(len(cs))) + "List.Forall₂.nil" + ")" * len(cs)
    o = [HDR + f"import Solution.SymStagedCert.{t}Run6\n" +
         "".join(f"import Solution.SymStagedCert.{t}Prof6G{gi}\n" for gi in range(len(groups))) + "\n"
         f"/-! # V2ℓ: the certified moment profile of `{t}` after six factors (generated by\n"
         "`specs/checks/sym_staged_v2l_demo.py`) -/\n\nnamespace BGP212.V2e\n\n" + run.opens,
         f"def {t}_P6 : List ((ℕ × ℕ) × ℚ) := {penc(P6)}\n",
         f"theorem {t}_pc6 : ProfCert {run.nE} {run.gE} {qlit(6)} {t}_P6 :=\n"
         f"  profCert_of_chunks _ _ _ [{', '.join(run.name(6, j) for j in range(len(cs)))}]\n"
         f"    [{', '.join(f'{t}_P6_{j}' for j in range(len(cs)))}] _ {t}_c6\n    {f2}\n    (by decide +kernel)\n",
         "end BGP212.V2e\n"]
    open(os.path.join(d, f"{t}Prof6.lean"), "w").write("\n".join(o))
    run.prof_groups = len(groups)


def merge_profiles(Ps):
    acc = {}
    for P in Ps:
        for ab, v in P:
            acc[ab] = acc.get(ab, Fr(0)) + v
    return sorted(acc.items())


def tenc(T):
    out = []
    for (a, b, m, n), v in T:
        v = Fr(v)
        out.append(f"[{a}, {b}, {m}, {n}, {0 if v >= 0 else 1}, {abs(v.numerator)}, {v.denominator}]")
    return "decTable [" + ",\n    ".join(out) + "]"


def write_tables(root, tables):
    for tag, (a1, l1, a2, l2), T in tables:
        ll = lambda l: "[" + ", ".join(map(str, l)) + "]"  # noqa: E731
        ws = f"[((1 : ℚ), {a1}, {ll(l1)}, {a2}, {ll(l2)})]"
        imports = ("import Solution.SymStagedRuns\nimport Solution.SymReduceDemo2\n" if tag != "P222"
                   else "import Solution.SymStagedProfiles\n")
        TB, RR, RC, EQ = (("stagedTable", "T3_R", "T3_R_cert", "genPieceWith_eq_stagedTable") if tag != "P222"
                          else ("profTable", "T3_P", "T3_P_cert", "genPieceWith_eq_profTable"))
        tl = f"({table_lit(T)} : List (MKey × ℚ))" if tag != "P222" else "(" + tenc(T) + ")"
        o = [HDR + imports + "\n" +
             f"/-! # V2ℓ: the staged table of `J_T[{tag}]`-type piece `(6, 3)` at Table 3\n\n(generated by "
             "`specs/checks/sym_staged_v2l_demo.py`) -/\n\nnamespace BGP212.V2e\n\nopen BGP212.Params\n",
             f"theorem tabS_{tag}_6_3 : {TB} 44 6 3 g {RR} {ws} =\n    {tl} := by\n"
             "  decide +kernel\n",
             f"theorem genPiece{tag}_6_3_staged_expansion : genPiece 44 6 3 g L τ C {a1} {ll(l1)} {a2} {ll(l2)} =\n"
             f"    tableVal {tl}\n      (fun A B m n => pieceMn 44 6 3 A B g L τ C m n) :=\n"
             f"  ({EQ} 44 6 3 g {RR} {RC} _ {a1} {ll(l1)} {a2} {ll(l2)}).trans\n"
             f"    (congrArg (fun T => tableVal T (fun A B m n => pieceMn 44 6 3 A B g L τ C m n)) tabS_{tag}_6_3)\n"]
        if tag == "PP":
            o.append("/-- The table is V2k's `tab_PP_6_3`; with V2k's `tv_PP_6_3` this is V2i's `gpPP_6_3`. -/\n"
                     f"theorem genPiecePP_6_3_staged : genPiece 44 6 3 g L τ C 0 [2] 0 [2] =\n"
                     f"    {lit(sum(v * Q.pieceMn(6, 3, *s) for s, v in T if v != 0))} :=\n"
                     "  genPiecePP_6_3_staged_expansion.trans tv_PP_6_3\n\n"
                     "theorem genPiecePP_6_3_staged_same_as_v2i : genPiecePP_6_3_staged = gpPP_6_3 := rfl\n")
        if tag == "P22":
            o.append("/-- The same statement as V2k's `genPieceP22_6_3_expansion`. -/\n"
                     "theorem genPieceP22_6_3_staged_same : genPieceP22_6_3_staged_expansion =\n"
                     "    genPieceP22_6_3_expansion := rfl\n")
        o.append("end BGP212.V2e\n")
        name = {"PP": "SymStagedDemo4", "P22": "SymStagedDemo5", "P222": "SymStagedDemo6"}[tag]
        open(os.path.join(root, "Solution", f"{name}.lean"), "w").write("\n".join(o))


