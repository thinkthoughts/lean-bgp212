#!/usr/bin/env python3
"""Emit V2ℓ's staged certificates and demonstrations.

Runs of shifted power sums P̂₂^k (k ≤ 6), certified one factor at a time; from k = 5 on, each step
is certified chunk by chunk (one `lean` process per chunk) followed by one merge:

  * run `Dm`: the example data of V2k (`demoN = (3, 2, 4)`, shift 3/10);
  * run `T3`: Table 3, piece (6, 3) (`clsCount 44 6 3 = (6, 3, 35)`, shift g = 41/625).

Files (directory Solution/SymStagedCert/):
  <X>Run1.lean          states L₁ … L₄ (L₄ in chunks), steps 1–4, chains c₁ … c₄;
  <X>Run<k>C<j>.lean    the step k of chunk j of L_{k−1} (k = 5, 6);
  <X>Run<k>.lean        L_k in chunks, the merge, the step certificate and the chain c_k.
Demonstrations: Solution/SymStagedDemo1.lean (small chains, permutation), SymStagedDemo2.lean
(example data, degrees 10 and 12), SymStagedDemo3.lean … Demo5.lean (Table 3 tables).

Usage: python3 -I specs/checks/sym_staged_v2l_demo.py [root]
"""
