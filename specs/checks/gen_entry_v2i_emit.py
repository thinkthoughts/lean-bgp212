#!/usr/bin/env python3
"""Emit the kernel certificate for V2i's worked entries at Table 3.

Entries (`genEntryVal 44 g L τ C a₁ l₁ a₂ l₂`, BGP212/GenEntry.lean):
  PP  = J_T[P₂, P₂]        (0, [2], 0, [2])  cross-check against V2h's p2p2EntryVal
  P4  = J_T[P₄, 1]         (0, [4], 0, [])
  P22 = J_T[P_{(2,2)}, 1]  (0, [2, 2], 0, [])
  LP  = J_T[L − P₁, 1]     (1, [], 0, [])

Moment table per piece (moments are certified once and shared by all entries):
  (A, B, 2, 0)  V2h's `mom_r_k_A_B` (pieceM … 2) through `pieceMn_zero`;
  (eR, eS, 4, 0) V2h's `e4_r_k_eR_eS` (pieceE … 4) through `pieceMn_of_pieceE`;
  (0, 0, 6, 0)  V2h's `u6_r_k` (pieceJ … 6 0) through `pieceMn_zero_zero`;
  (0, 0, 2, 1), (0, 0, 3, 0)  new, `mn_r_k_…` by `decide +kernel`.
Each piece value `genPiece 44 r k …` is then `genPieceWith` against `tableFn` of these numerals
(`tableFn_eq`), evaluated by `decide +kernel` (only coefficients and placements, no cells).

Files: Solution/GenEntryCert0.lean … GenEntryCert13.lean (one per row, each importing V2h's row
file), Solution/GenEntryCertSum.lean (rows and totals).

Usage: python3 -I specs/checks/gen_entry_v2i_emit.py [outdir] [--test r:k,... FILE]
"""
import os
import sys
from fractions import Fraction as Fr
from math import comb, factorial as fact

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import marginal_entry_v2f_emit as E  # noqa: E402
import power_sum_entry_v2g_emit as P  # noqa: E402
import gen_entry_v2i_model as Q  # noqa: E402

PIECES = [(r, k) for r in range(14) for k in range(16 - r)]
ENTRIES = [("PP", (0, [2], 0, [2])), ("P4", (0, [4], 0, [])), ("P22", (0, [2, 2], 0, [])),
           ("LP", (1, [], 0, []))]
NEW = [(0, 0, 2, 1), (0, 0, 3, 0)]


def lit(x):
    x = Fr(x)
    return f"({x.numerator} : ℚ)" if x.denominator == 1 else f"({x.numerator} / {x.denominator} : ℚ)"


def lean_list(l):
    return "[" + ", ".join(str(q) for q in l) + "]"


def key_entry(r, k, key, val):
    """(Lean value expression, proof term) of one table entry."""
    A, B, m, n = key
    if (m, n) == (2, 0):
        return lit(val), f"(pieceMn_zero 44 {r} {k} {A} {B} g L τ C 2).trans mom_{r}_{k}_{A}_{B}"
    if (m, n) == (4, 0):
        e4 = P.pieceE(r, k, A, B, 4)
        d = (1 if r == 0 else fact(A)) * fact(B)
        assert e4 / d == val, (r, k, key)
        expr = (f"{lit(e4)} / (((if {r} = 0 then 1 else Nat.factorial {A}) * Nat.factorial {B} : ℕ) : ℚ)")
        return expr, f"pieceMn_of_pieceE 44 {r} {k} {A} {B} g L τ C 4 _ e4_{r}_{k}_{A}_{B}"
    if key == (0, 0, 6, 0):
        return lit(val), f"(pieceMn_zero_zero 44 {r} {k} g L τ C 6 0).trans u6_{r}_{k}"
    if key in NEW:
        return lit(val), f"mn_{r}_{k}_{A}_{B}_{m}_{n}"
    raise KeyError(key)


def piece_lemmas(r, k, vals, out):
    for key in NEW:
        A, B, m, n = key
        out.append(f"theorem mn_{r}_{k}_{A}_{B}_{m}_{n} : pieceMn 44 {r} {k} {A} {B} g L τ C {m} {n} = "
                   f"{lit(vals[key])} := by\n  decide +kernel\n")
    for name, args in ENTRIES:
        ks = Q.keys(*args)
        ents = [key_entry(r, k, kk, vals[kk]) for kk in ks]
        table = "[" + ", ".join(f"(({kk[0]}, {kk[1]}, {kk[2]}, {kk[3]}), {e[0]})" for kk, e in zip(ks, ents)) + "]"
        proof = "fun _ h => absurd h List.not_mem_nil"
        for e in reversed(ents):
            proof = f"List.forall_mem_cons.2 ⟨{e[1]}, {proof}⟩"
        v = Q.genPiece(r, k, *args, Mo=lambda A, B, m, n: vals[(A, B, m, n)])
        a1, l1, a2, l2 = args
        out.append(
            f"theorem gp{name}_{r}_{k} : genPiece 44 {r} {k} g L τ C {a1} {lean_list(l1)} {a2} {lean_list(l2)} = "
            f"{lit(v)} := by\n"
            f"  rw [genPiece, ← tableFn_eq {table}\n"
            f"    (fun A B m n => pieceMn 44 {r} {k} A B g L τ C m n)\n"
            f"    ({proof})]\n"
            "  decide +kernel\n")


