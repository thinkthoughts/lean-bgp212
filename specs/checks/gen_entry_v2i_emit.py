def all_values():
    keys = sorted({kk for _, args in ENTRIES for kk in Q.keys(*args)})
    return {rk: {kk: Q.pieceMn(*rk, *kk) for kk in keys} for rk in PIECES}


def row_file(r, cache):
    out = [HDR, "import Solution.GenEntryTable\n", f"import Solution.PowerSumSquareCert{r}\n",
           f"/-! # V2i: the kernel certificate for the worked `J_T` entries at Table 3, row `r = {r}`\n\n"
           "COMPUTATIONAL CERTIFICATE (generated by `specs/checks/gen_entry_v2i_emit.py`). For each nonempty\n"
           "piece `(r, k)`: the new moments `pieceMn … 2 1` and `pieceMn … 3 0` (`mn_r_k_…`), and the piece\n"
           "values `genPiece` of the entries `PP`, `P4`, `P22`, `LP` against a table of certified moments\n"
           "(V2h's for the powers `U²`, `U⁴`, `U⁶`), each by `decide +kernel`. -/\n",
           "namespace BGP212.V2e\n", "open BGP212.Params\n"]
    for (rr, k) in PIECES:
        if rr == r:
            piece_lemmas(r, k, cache[(r, k)], out)
    out.append("end BGP212.V2e\n")
    return "\n".join(out)


def sum_file(cache):
    out = [HDR, "import Solution.PowerSumEntryCert\nimport Solution.PowerSumSquareCertSum\n" +
           "".join(f"import Solution.GenEntryCert{r}\n" for r in range(14)),
           "/-! # V2i: the kernel certificate for the worked `J_T` entries at Table 3 (rows and totals)\n\n"
           "COMPUTATIONAL CERTIFICATE (generated by `specs/checks/gen_entry_v2i_emit.py`). Pieces with\n"
           "`r + k ≥ 16` or `r ≥ 14` are empty at Table 3 (V2g's `cond_tail`, `cond_high`; `genPiece_empty`);\n"
           "rows and totals are assembled by `decide +kernel` on numerals. -/\n",
           "namespace BGP212.V2e\n", "open BGP212.Params\n"]
    totals = {}
    for name, args in ENTRIES:
        a1, l1, a2, l2 = args
        A = f"{a1} {lean_list(l1)} {a2} {lean_list(l2)}"
        out.append(f"theorem genRow{name}_high (r : ℕ) (h : 14 ≤ r) : genRow 44 r g L τ C {A} = 0 :=\n"
                   f"  Finset.sum_eq_zero fun k _ => by rw [genPiece_empty 44 r k g L τ C (cond_high r k h), mul_zero]\n")
        rows = {}
        for r in range(14):
            K = 16 - r
            tail = (44 - r + 1) - K
            vals = {k: Q.genPiece(r, k, *args, Mo=lambda A_, B_, m, n, r=r, k=k: cache[(r, k)][(A_, B_, m, n)])
                    for k in range(K)}
            rows[r] = sum(comb(44 - r, k) * (-1) ** k * vals[k] for k in range(K))
            names = ", ".join(f"gp{name}_{r}_{k}" for k in range(K))
            out.append(
                f"theorem genRow{name}_{r} : genRow 44 {r} g L τ C {A} = {lit(rows[r])} := by\n"
                f"  have hz : ∑ x ∈ Finset.range {tail}, (((44 - {r}).choose ({K} + x) : ℕ) : ℚ) *\n"
                f"      (-1) ^ ({K} + x) * genPiece 44 {r} ({K} + x) g L τ C {A} = 0 :=\n"
                f"    Finset.sum_eq_zero fun x _ => by\n"
                f"      rw [genPiece_empty 44 {r} ({K} + x) g L τ C (cond_tail {r} ({K} + x) (by omega)), mul_zero]\n"
                f"  rw [genRow, show 44 - {r} + 1 = {K} + {tail} from rfl, Finset.sum_range_add, hz, add_zero]\n"
                f"  simp only [Finset.sum_range_succ, Finset.sum_range_zero, {names}]\n"
                "  decide +kernel\n")
        tot = 45 * sum(comb(44, r) * rows[r] for r in range(14))
        totals[name] = tot
        out.append(
            f"theorem genEntry{name}_table3 : genEntryVal 44 g L τ C {A} = {lit(tot)} := by\n"
            f"  have hz : ∑ x ∈ Finset.range 31, ((Nat.choose 44 (14 + x) : ℕ) : ℚ) *\n"
            f"      genRow 44 (14 + x) g L τ C {A} = 0 :=\n"
            f"    Finset.sum_eq_zero fun x _ => by rw [genRow{name}_high (14 + x) (by omega), mul_zero]\n"
            f"  rw [genEntryVal, show 44 + 1 = 14 + 31 from rfl, Finset.sum_range_add, hz, add_zero]\n"
            "  simp only [Finset.sum_range_succ, Finset.sum_range_zero, "
            + ", ".join(f"genRow{name}_{r}" for r in range(14)) + "]\n"
            "  decide +kernel\n")
    out.append("/-- The general closed form reproduces V2h's certified `J_T[P₂, P₂]`. -/\n"
               "theorem genEntryPP_eq_v2h : genEntryVal 44 g L τ C 0 [2] 0 [2] = p2p2EntryVal 44 g L τ C := by\n"
               "  rw [genEntryPP_table3, p2p2EntryVal_table3]\n")
    out.append("end BGP212.V2e\n")
    return "\n".join(out), totals


if __name__ == "__main__":
    if "--test" in sys.argv:
        i = sys.argv.index("--test")
        ps = [tuple(int(v) for v in x.split(":")) for x in sys.argv[i + 1].split(",")]
        keys = sorted({kk for _, args in ENTRIES for kk in Q.keys(*args)})
        out = [HDR, "import Solution.GenEntryTable\n"] + [f"import Solution.PowerSumSquareCert{r}\n"
                                                        for r in sorted({r for r, _ in ps})]
        out += ["namespace BGP212.V2e\n", "open BGP212.Params\n"]
        for (r, k) in ps:
            piece_lemmas(r, k, {kk: Q.pieceMn(r, k, *kk) for kk in keys}, out)
        out.append("end BGP212.V2e\n")
        open(sys.argv[i + 2], "w").write("\n".join(out))
        sys.exit(0)
    outdir = sys.argv[1] if len(sys.argv) > 1 else "Solution"
    cache = all_values()
    for r in range(14):
        open(os.path.join(outdir, f"GenEntryCert{r}.lean"), "w").write(row_file(r, cache))
    text, totals = sum_file(cache)
    open(os.path.join(outdir, "GenEntryCertSum.lean"), "w").write(text)
    for name, v in totals.items():
        print(name, float(v), v.numerator, "/", v.denominator)
